package es.urjc.kombo.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.util.List;
import java.util.Optional;

import org.hibernate.engine.jdbc.proxy.BlobProxy;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mapstruct.factory.Mappers;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.crypto.password.PasswordEncoder;

import es.urjc.kombo.dto.AddressesUpdateDTO;
import es.urjc.kombo.dto.PasswordChangeDTO;
import es.urjc.kombo.dto.ProfileUpdateDTO;
import es.urjc.kombo.dto.SignUpRequestDTO;
import es.urjc.kombo.dto.UserCreationRequestDTO;
import es.urjc.kombo.dto.UserDTO;
import es.urjc.kombo.dto.UserMapper;
import es.urjc.kombo.model.Image;
import es.urjc.kombo.model.User;
import es.urjc.kombo.repository.OrderRepository;
import es.urjc.kombo.repository.UserRepository;

@ExtendWith(MockitoExtension.class)
class UserServiceTest {

    // Fake repository and encoder: no database is used
    @Mock
    private UserRepository userRepository;

    @Mock
    private PasswordEncoder passwordEncoder;

    @Mock
    private OrderRepository orderRepository;

    private UserService userService;

    @BeforeEach
    void setUp() {
        // Real mapper generated by MapStruct
        userService = new UserService(userRepository, Mappers.getMapper(UserMapper.class), passwordEncoder,
                new ImageService(), orderRepository);
    }

    @Test
    void signUpSavesACustomerWithTheEncodedPassword() {
        when(userRepository.existsByEmail("ana@example.com")).thenReturn(false);
        when(passwordEncoder.encode("secret-password")).thenReturn("encoded-password");
        when(userRepository.save(any(User.class))).thenAnswer(invocation -> invocation.getArgument(0));

        UserDTO user = userService.signUp(new SignUpRequestDTO(" Ana ", "Martín", " ana@example.com ", "600123456",
                "secret-password"));

        ArgumentCaptor<User> saved = ArgumentCaptor.forClass(User.class);
        verify(userRepository).save(saved.capture());
        assertThat(saved.getValue().getPassword()).isEqualTo("encoded-password");
        assertThat(saved.getValue().getRole()).isEqualTo(User.Role.CUSTOMER);
        // Spaces around the name and the email are removed
        assertThat(user.name()).isEqualTo("Ana");
        assertThat(user.email()).isEqualTo("ana@example.com");
        assertThat(user.role()).isEqualTo(User.Role.CUSTOMER);
    }

    @Test
    void signUpStoresEmptyOptionalFieldsAsNull() {
        when(userRepository.save(any(User.class))).thenAnswer(invocation -> invocation.getArgument(0));

        UserDTO user = userService.signUp(new SignUpRequestDTO("Ana", " ", "ana@example.com", "", "secret-password"));

        assertThat(user.surname()).isNull();
        assertThat(user.phone()).isNull();
    }

    @Test
    void signUpRejectsAnEmailThatIsAlreadyRegistered() {
        when(userRepository.existsByEmail("customer@kombo.com")).thenReturn(true);

        assertThatThrownBy(() -> userService.signUp(new SignUpRequestDTO("Ana", null, "customer@kombo.com", null,
                "secret-password")))
                .isInstanceOf(EmailAlreadyUsedException.class)
                .hasMessage("The email customer@kombo.com is already registered");
        verify(userRepository, never()).save(any());
    }

    @Test
    void createUserSavesAnEmployeeWithTheEncodedPassword() {
        when(userRepository.existsByEmail("luis@kombo.com")).thenReturn(false);
        when(passwordEncoder.encode("secret-password")).thenReturn("encoded-password");
        when(userRepository.save(any(User.class))).thenAnswer(invocation -> invocation.getArgument(0));

        UserDTO user = userService.createUser(new UserCreationRequestDTO(" Luis ", "", " luis@kombo.com ", null,
                "secret-password", "EMPLOYEE"));

        ArgumentCaptor<User> saved = ArgumentCaptor.forClass(User.class);
        verify(userRepository).save(saved.capture());
        assertThat(saved.getValue().getPassword()).isEqualTo("encoded-password");
        assertThat(user.role()).isEqualTo(User.Role.EMPLOYEE);
        assertThat(user.name()).isEqualTo("Luis");
        assertThat(user.surname()).isNull();
        assertThat(user.email()).isEqualTo("luis@kombo.com");
    }

    @Test
    void createUserCanAlsoCreateACustomer() {
        when(userRepository.save(any(User.class))).thenAnswer(invocation -> invocation.getArgument(0));

        UserDTO user = userService.createUser(new UserCreationRequestDTO("Ana", null, "ana@example.com", null,
                "secret-password", "CUSTOMER"));

        assertThat(user.role()).isEqualTo(User.Role.CUSTOMER);
    }

    @Test
    void createUserRejectsAnEmailThatIsAlreadyRegistered() {
        when(userRepository.existsByEmail("employee@kombo.com")).thenReturn(true);

        assertThatThrownBy(() -> userService.createUser(new UserCreationRequestDTO("Luis", null, "employee@kombo.com",
                null, "secret-password", "EMPLOYEE")))
                .isInstanceOf(EmailAlreadyUsedException.class);
        verify(userRepository, never()).save(any());
    }

    @Test
    void updateProfileChangesTheDataAndKeepsTheEmail() {
        User user = customer();
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));

        UserDTO updated = userService.updateProfile(2L, new ProfileUpdateDTO(" Ana María ", " ", "611222333"));

        assertThat(updated.name()).isEqualTo("Ana María");
        assertThat(updated.surname()).isNull();
        assertThat(updated.phone()).isEqualTo("611222333");
        assertThat(updated.email()).isEqualTo("ana@example.com");
    }

    @Test
    void updateProfileOfAUserThatDoesNotExistFails() {
        when(userRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> userService.updateProfile(99L, new ProfileUpdateDTO("Ana", null, null)))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("User 99 not found");
    }

    @Test
    void changePasswordStoresTheNewPasswordEncoded() {
        User user = customer();
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));
        when(passwordEncoder.matches("secret-password", "encoded-password")).thenReturn(true);
        when(passwordEncoder.encode("new-secret-password")).thenReturn("new-encoded-password");

        userService.changePassword(2L, new PasswordChangeDTO("secret-password", "new-secret-password"));

        assertThat(user.getPassword()).isEqualTo("new-encoded-password");
    }

    @Test
    void changePasswordRejectsAWrongCurrentPassword() {
        User user = customer();
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));
        when(passwordEncoder.matches("wrong-password", "encoded-password")).thenReturn(false);

        assertThatThrownBy(() -> userService.changePassword(2L,
                new PasswordChangeDTO("wrong-password", "new-secret-password")))
                .isInstanceOf(WrongPasswordException.class);
        assertThat(user.getPassword()).isEqualTo("encoded-password");
        verify(passwordEncoder, never()).encode(any());
    }

    @Test
    void updateAddressesReplacesTheListWithoutBlanksOrRepetitions() {
        User user = customer();
        user.addAddress("Calle Vieja 1");
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));

        UserDTO updated = userService.updateAddresses(2L,
                new AddressesUpdateDTO(List.of(" Calle Mayor 1 ", "Calle Luna 2", "Calle Mayor 1")));

        assertThat(updated.addresses()).containsExactly("Calle Mayor 1", "Calle Luna 2");
        assertThat(user.getAddresses()).containsExactly("Calle Mayor 1", "Calle Luna 2");
    }

    @Test
    void updateImageStoresThePictureOfTheUser() {
        User user = customer();
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));

        UserDTO updated = userService.updateImage(2L,
                new MockMultipartFile("image", "photo.jpg", "image/jpeg", ImageServiceTest.JPEG));

        assertThat(updated.imageId()).isNull(); // the id is given by the database when saving
        assertThat(user.getImage().getContentType()).isEqualTo("image/jpeg");
        assertThat(user.getImage().getText()).isEqualTo("Ana");
    }

    @Test
    void findImageOfAUserWithoutPictureFails() {
        when(userRepository.findById(2L)).thenReturn(Optional.of(customer()));

        assertThatThrownBy(() -> userService.findImage(2L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("User 2 has no image");
    }

    @Test
    void deleteImageRemovesThePicture() {
        User user = customer();
        user.setImage(new Image(BlobProxy.generateProxy(ImageServiceTest.JPEG), "image/jpeg", "Ana"));
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));

        userService.deleteImage(2L);

        assertThat(user.getImage()).isNull();
    }

    @Test
    void deleteAccountKeepsTheOrdersWithoutTheCustomerAndDeletesTheUser() {
        User user = customer();
        when(userRepository.findById(2L)).thenReturn(Optional.of(user));

        userService.deleteAccount(2L);

        verify(orderRepository).anonymizeOrdersOf(user);
        verify(userRepository).delete(user);
    }

    @Test
    void theAccountOfTheAdministratorCannotBeDeleted() {
        User admin = new User("Admin", "Kombo", "admin@kombo.com", null, "encoded-password", User.Role.ADMIN);
        when(userRepository.findById(1L)).thenReturn(Optional.of(admin));

        assertThatThrownBy(() -> userService.deleteAccount(1L)).isInstanceOf(AccessDeniedException.class);
        verify(userRepository, never()).delete(any());
        verify(orderRepository, never()).anonymizeOrdersOf(any());
    }

    private static User customer() {
        return new User("Ana", "Martín", "ana@example.com", "600123456", "encoded-password", User.Role.CUSTOMER);
    }
}
