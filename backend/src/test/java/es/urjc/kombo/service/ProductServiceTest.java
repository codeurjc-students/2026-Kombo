package es.urjc.kombo.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.when;

import java.io.IOException;
import java.math.BigDecimal;
import java.util.List;
import java.util.Optional;

import org.hibernate.engine.jdbc.proxy.BlobProxy;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mapstruct.factory.Mappers;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;

import es.urjc.kombo.dto.ImageFileDTO;
import es.urjc.kombo.dto.ProductDTO;
import es.urjc.kombo.dto.ProductMapper;
import es.urjc.kombo.model.Image;
import es.urjc.kombo.model.Product;
import es.urjc.kombo.repository.ProductRepository;

@ExtendWith(MockitoExtension.class)
class ProductServiceTest {

    // Fake repository: no database is used
    @Mock
    private ProductRepository productRepository;

    private ProductService productService;

    private final Pageable pageable = PageRequest.of(0, 10);

    @BeforeEach
    void setUp() {
        // Real mapper generated by MapStruct
        productService = new ProductService(productRepository, Mappers.getMapper(ProductMapper.class));
    }

    @Test
    void findActiveWithoutCategoryReturnsAllActiveProducts() {
        List<Product> products = List.of(new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers"),
                new Product("Test Drink", new BigDecimal("2.70"), "Test description", "Drinks"));
        when(productRepository.findByActiveTrue(pageable)).thenReturn(new PageImpl<>(products, pageable, 2));

        Page<ProductDTO> result = productService.findActive(null, pageable);

        assertThat(result.getContent()).extracting(ProductDTO::name).containsExactly("Test Burger", "Test Drink");
        assertThat(result.getTotalElements()).isEqualTo(2);
    }

    @Test
    void findActiveWithCategoryFiltersByCategory() {
        List<Product> drinks = List.of(new Product("Test Drink", new BigDecimal("2.70"), "Test description", "Drinks"));
        when(productRepository.findByActiveTrueAndCategoryIgnoreCase("Drinks", pageable))
                .thenReturn(new PageImpl<>(drinks, pageable, 1));

        Page<ProductDTO> result = productService.findActive("Drinks", pageable);

        assertThat(result.getContent()).extracting(ProductDTO::name).containsExactly("Test Drink");
    }

    // A blank category (for example "?category=") is the same as no category: the whole menu
    @Test
    void findActiveWithBlankCategoryReturnsAllActiveProducts() {
        List<Product> products = List.of(new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers"));
        when(productRepository.findByActiveTrue(pageable)).thenReturn(new PageImpl<>(products, pageable, 1));

        Page<ProductDTO> result = productService.findActive(" ", pageable);

        assertThat(result.getContent()).extracting(ProductDTO::name).containsExactly("Test Burger");
    }

    @Test
    void findByIdThrowsWhenTheProductDoesNotExist() {
        when(productRepository.findByIdAndActiveTrue(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> productService.findById(99L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Product 99 not found");
    }

    @Test
    void findImageReturnsTheImageOfTheProduct() throws IOException {
        Product burger = new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers");
        burger.setImage(new Image(BlobProxy.generateProxy(new byte[] {7, 8, 9}), "image/jpeg", "Test Burger"));
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger));

        ImageFileDTO image = productService.findImage(1L);

        assertThat(image.contentType()).isEqualTo("image/jpeg");
        assertThat(image.content().getContentAsByteArray()).containsExactly(7, 8, 9);
    }

    @Test
    void findImageThrowsWhenTheProductHasNoImage() {
        Product burger = new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers");
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger));

        assertThatThrownBy(() -> productService.findImage(1L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Product 1 has no image");
    }
}
