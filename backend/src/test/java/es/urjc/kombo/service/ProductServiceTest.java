@ExtendWith(MockitoExtension.class)
class ProductServiceTest {

    // Fake repositories: no database is used
    @Mock
    private ProductRepository productRepository;

    @Mock
    private ComboRepository comboRepository;

    @Mock
    private IngredientRepository ingredientRepository;

    private ProductService productService;

    private final Pageable pageable = PageRequest.of(0, 10);

    @BeforeEach
    void setUp() {
        // Real mapper generated by MapStruct
        productService = new ProductService(productRepository, comboRepository, ingredientRepository,
                Mappers.getMapper(ProductMapper.class), new ImageService());
    }

    @Test
    void findActiveWithoutCategoryReturnsAllActiveProducts() {
        List<Product> products = List.of(new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers"),
                new Product("Test Drink", new BigDecimal("2.70"), "Test description", "Drinks"));
        when(productRepository.findByActiveTrue(pageable)).thenReturn(new PageImpl<>(products, pageable, 2));

        Page<ProductDTO> result = productService.findActive(null, pageable);

        assertThat(result.getContent()).extracting(ProductDTO::name).containsExactly("Test Burger", "Test Drink");
        assertThat(result.getTotalElements()).isEqualTo(2);
    }

    @Test
    void findActiveWithCategoryFiltersByCategory() {
        List<Product> drinks = List.of(new Product("Test Drink", new BigDecimal("2.70"), "Test description", "Drinks"));
        when(productRepository.findByActiveTrueAndCategoryIgnoreCase("Drinks", pageable))
                .thenReturn(new PageImpl<>(drinks, pageable, 1));

        Page<ProductDTO> result = productService.findActive("Drinks", pageable);

        assertThat(result.getContent()).extracting(ProductDTO::name).containsExactly("Test Drink");
    }

    // A blank category (for example "?category=") is the same as no category: the whole menu
    @Test
    void findActiveWithBlankCategoryReturnsAllActiveProducts() {
        List<Product> products = List.of(new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers"));
        when(productRepository.findByActiveTrue(pageable)).thenReturn(new PageImpl<>(products, pageable, 1));

        Page<ProductDTO> result = productService.findActive(" ", pageable);

        assertThat(result.getContent()).extracting(ProductDTO::name).containsExactly("Test Burger");
    }

    @Test
    void findByIdReturnsTheIngredientsOfAProduct() {
        Product burger = new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers");
        burger.addIngredient(new Ingredient("Bread", "units", 100, 20), 1);
        burger.addIngredient(new Ingredient("Beef", "g", 5000, 1000), 150);
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger));

        ProductDetailDTO detail = productService.findById(1L);

        assertThat(detail.name()).isEqualTo("Test Burger");
        assertThat(detail.combo()).isFalse();
        assertThat(detail.products()).isEmpty();
        // Sorted by name
        assertThat(detail.ingredients()).extracting(ProductIngredientDTO::name, ProductIngredientDTO::quantity)
                .containsExactly(tuple("Beef", 150), tuple("Bread", 1));
    }

    // A combo lists its products and the ingredients of all of them, multiplied by the units of each product
    @Test
    void findByIdReturnsTheProductsAndIngredientsOfACombo() {
        Ingredient bread = new Ingredient("Bread", "units", 100, 20);
        Product burger = new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers");
        burger.addIngredient(bread, 1);
        Product drink = new Product("Test Drink", new BigDecimal("1.50"), "Test description", "Drinks");
        Combo menu = new Combo("Test Menu", new BigDecimal("9.00"), "Two burgers and a drink", "Combos");
        menu.addProduct(burger, 2);
        menu.addProduct(drink, 1);
        when(productRepository.findByIdAndActiveTrue(3L)).thenReturn(Optional.of(menu));

        ProductDetailDTO detail = productService.findById(3L);

        assertThat(detail.combo()).isTrue();
        assertThat(detail.products()).extracting(item -> item.product().name(), item -> item.quantity())
                .containsExactly(tuple("Test Burger", 2), tuple("Test Drink", 1));
        assertThat(detail.ingredients()).extracting(ProductIngredientDTO::name, ProductIngredientDTO::quantity)
                .containsExactly(tuple("Bread", 2));
    }

    @Test
    void findByIdThrowsWhenTheProductDoesNotExist() {
        when(productRepository.findByIdAndActiveTrue(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> productService.findById(99L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Product 99 not found");
    }

    @Test
    void findImageReturnsTheImageOfTheProduct() throws IOException {
        Product burger = new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers");
        burger.setImage(new Image(BlobProxy.generateProxy(new byte[] {7, 8, 9}), "image/jpeg", "Test Burger"));
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger));

        ImageFileDTO image = productService.findImage(1L);

        assertThat(image.contentType()).isEqualTo("image/jpeg");
        assertThat(image.content().getContentAsByteArray()).containsExactly(7, 8, 9);
    }

    @Test
    void findImageThrowsWhenTheProductHasNoImage() {
        Product burger = new Product("Test Burger", new BigDecimal("5.00"), "Test description", "Burgers");
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger));

        assertThatThrownBy(() -> productService.findImage(1L))
                .isInstanceOf(ResourceNotFoundException.class)
                .hasMessage("Product 1 has no image");
    }

    // Management of the administrator

    private static final BigDecimal PRICE = new BigDecimal("6.50");

    private static Product burger() {
        return new Product("Hamburguesa", new BigDecimal("5.00"), null, "Burgers");
    }

    private static Product drink() {
        return new Product("Refresco", new BigDecimal("2.00"), null, "Drinks");
    }

    @Test
    void createProductSavesTheProductWithItsIngredients() {
        Ingredient bread = new Ingredient("Pan", "unidades", 10, 2);
        when(ingredientRepository.findById(1L)).thenReturn(Optional.of(bread));
        when(productRepository.save(any(Product.class))).thenAnswer(invocation -> invocation.getArgument(0));

        AdminProductDTO product = productService.createProduct(new ProductRequestDTO(" Hamburguesa doble ", PRICE,
                " ", "Burgers", List.of(new IngredientQuantityDTO(1L, 2))));

        assertThat(product.name()).isEqualTo("Hamburguesa doble");
        assertThat(product.description()).isNull();
        assertThat(product.active()).isTrue();
        assertThat(product.combo()).isFalse();
        assertThat(product.imageId()).isNull();
        assertThat(product.ingredients()).extracting(ProductIngredientDTO::name, ProductIngredientDTO::quantity)
                .containsExactly(tuple("Pan", 2));
    }

    @Test
    void createProductRejectsAnIngredientThatDoesNotExistOrIsRepeated() {
        when(ingredientRepository.findById(1L)).thenReturn(Optional.of(new Ingredient("Pan", "unidades", 10, 2)));
        when(ingredientRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> productService.createProduct(new ProductRequestDTO("Hamburguesa", PRICE, null,
                "Burgers", List.of(new IngredientQuantityDTO(99L, 1)))))
                .isInstanceOf(InvalidProductException.class)
                .hasMessage("ingredients: ingredient 99 does not exist");
        assertThatThrownBy(() -> productService.createProduct(new ProductRequestDTO("Hamburguesa", PRICE, null,
                "Burgers", List.of(new IngredientQuantityDTO(1L, 1), new IngredientQuantityDTO(1L, 2)))))
                .isInstanceOf(InvalidProductException.class)
                .hasMessage("ingredients: ingredient 1 is repeated");
        verify(productRepository, never()).save(any());
    }

    @Test
    void updateProductChangesTheDataButNotAKombo() {
        Product burger = burger();
        when(productRepository.findById(1L)).thenReturn(Optional.of(burger));
        when(productRepository.findById(2L)).thenReturn(Optional.of(new Combo("Kombo", PRICE, null, "Combos")));
        ProductRequestDTO request = new ProductRequestDTO("Hamburguesa XL", new BigDecimal("7.25"), "Grande",
                "Burgers", List.of());

        AdminProductDTO updated = productService.updateProduct(1L, request);

        assertThat(updated.name()).isEqualTo("Hamburguesa XL");
        assertThat(updated.price()).isEqualByComparingTo("7.25");
        assertThat(updated.ingredients()).isEmpty();
        assertThatThrownBy(() -> productService.updateProduct(2L, request))
                .isInstanceOf(InvalidProductException.class);
    }

    @Test
    void createComboSavesItsProductsWithTheCategoryOfTheKombos() {
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger()));
        when(productRepository.findByIdAndActiveTrue(2L)).thenReturn(Optional.of(drink()));
        when(comboRepository.save(any(Combo.class))).thenAnswer(invocation -> invocation.getArgument(0));

        AdminProductDTO combo = productService.createCombo(new ComboRequestDTO("Kombo", PRICE, null,
                List.of(new ComboItemRequestDTO(1L, 1), new ComboItemRequestDTO(2L, 1))));

        assertThat(combo.combo()).isTrue();
        assertThat(combo.category()).isEqualTo("Combos");
        assertThat(combo.price()).isEqualByComparingTo(PRICE);
        assertThat(combo.products()).extracting(item -> item.product().name())
                .containsExactly("Hamburguesa", "Refresco");
    }

    @Test
    void aKomboOnlyHasActiveProductsThatAreNotKombosWithAtLeast2Units() {
        when(productRepository.findByIdAndActiveTrue(1L)).thenReturn(Optional.of(burger()));
        when(productRepository.findByIdAndActiveTrue(3L))
                .thenReturn(Optional.of(new Combo("Otro", PRICE, null, "Combos")));
        when(productRepository.findByIdAndActiveTrue(4L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> productService.createCombo(combo(new ComboItemRequestDTO(1L, 1))))
                .hasMessage("products: a combo has at least 2 units");
        assertThatThrownBy(() -> productService.createCombo(combo(new ComboItemRequestDTO(1L, 1),
                new ComboItemRequestDTO(3L, 1))))
                .hasMessage("products: a combo cannot include another combo");
        assertThatThrownBy(() -> productService.createCombo(combo(new ComboItemRequestDTO(4L, 2))))
                .hasMessage("products: product 4 does not exist or is not active");
        assertThatThrownBy(() -> productService.createCombo(combo(new ComboItemRequestDTO(1L, 1),
                new ComboItemRequestDTO(1L, 1))))
                .isInstanceOf(InvalidProductException.class)
                .hasMessage("products: product 1 is repeated");
        verify(comboRepository, never()).save(any());
        // Two units of the same product are a valid kombo
        when(comboRepository.save(any(Combo.class))).thenAnswer(invocation -> invocation.getArgument(0));
        assertThat(productService.createCombo(combo(new ComboItemRequestDTO(1L, 2))).products()).hasSize(1);
    }

    @Test
    void aProductInAnActiveKomboCannotBeDeactivated() {
        Product burger = burger();
        when(productRepository.findById(1L)).thenReturn(Optional.of(burger));
        when(comboRepository.findActiveCombosWith(burger))
                .thenReturn(List.of(new Combo("Kombo clásico", PRICE, null, "Combos")));

        assertThatThrownBy(() -> productService.changeActive(1L, false))
                .isInstanceOf(ProductInUseException.class)
                .hasMessage("The product is in active combos: Kombo clásico")
                .extracting(exception -> ((ProductInUseException) exception).getProducts())
                .isEqualTo(List.of(new ProductReferenceDTO(null, "Kombo clásico")));
        assertThat(burger.isActive()).isTrue();
    }

    @Test
    void aProductIsDeactivatedAndActivatedAgain() {
        Product drink = drink();
        when(productRepository.findById(2L)).thenReturn(Optional.of(drink));
        when(comboRepository.findActiveCombosWith(drink)).thenReturn(List.of());

        assertThat(productService.changeActive(2L, false).active()).isFalse();
        assertThat(productService.changeActive(2L, true).active()).isTrue();
    }

    @Test
    void aKomboWithADeactivatedProductCannotBeActivated() {
        Product drink = drink();
        Combo combo = new Combo("Kombo", PRICE, null, "Combos");
        combo.addProduct(burger(), 1);
        combo.addProduct(drink, 1);
        combo.setActive(false);
        drink.setActive(false);
        when(productRepository.findById(5L)).thenReturn(Optional.of(combo));

        assertThatThrownBy(() -> productService.changeActive(5L, true))
                .isInstanceOf(ProductInUseException.class)
                .hasMessage("The combo includes deactivated products: Refresco");

        drink.setActive(true);
        assertThat(productService.changeActive(5L, true).active()).isTrue();
        // A kombo is deactivated without checking anything
        assertThat(productService.changeActive(5L, false).active()).isFalse();
    }

    // Pictures of products have a limit of 10 MB, bigger than the 1 MB of profile pictures
    @Test
    void updateImageAcceptsAPictureOfMoreThan1Megabyte() {
        Product burger = burger();
        when(productRepository.findById(1L)).thenReturn(Optional.of(burger));
        byte[] picture = new byte[2 * 1024 * 1024];
        System.arraycopy(new byte[] {(byte) 0xFF, (byte) 0xD8, (byte) 0xFF}, 0, picture, 0, 3);

        productService.updateImage(1L, new MockMultipartFile("image", "photo.jpg", "image/jpeg", picture));

        assertThat(burger.getImage().getContentType()).isEqualTo("image/jpeg");
        verify(productRepository).flush();
    }

    @Test
    void theManagementAlsoFindsDeactivatedProducts() {
        Product burger = burger();
        burger.setActive(false);
        when(productRepository.findById(1L)).thenReturn(Optional.of(burger));
        when(productRepository.findForManagement(false, null, pageable))
                .thenReturn(new PageImpl<>(List.of(burger), pageable, 1));

        assertThat(productService.findForManagement(1L).active()).isFalse();
        assertThat(productService.findForManagement(false, null, pageable).getContent())
                .extracting(AdminProductDTO::name).containsExactly("Hamburguesa");
    }

    private static ComboRequestDTO combo(ComboItemRequestDTO... items) {
        return new ComboRequestDTO("Kombo", PRICE, null, List.of(items));
    }
}
